"""
Data loader for factory layout - loads from data.json
"""

import json
import os
from dataclasses import dataclass
from typing import List, Tuple

@dataclass
class Machine:
    """
    Machine definition for factory layout
    
    Attributes:
        name: Model name (e.g., "Wood Cutter")
        model: Exact model identifier (e.g., "WC-3000X")
        count: Number of machines of this type
        use: Description of what the machine does
        image: URL or path to single picture of the machine
        width: Width in meters
        height: Height in meters
    """
    name: str
    model: str
    count: int
    use: str
    image: str
    width: float  # meters
    height: float  # meters


def load_data(json_path: str = "data.json"):
    """Load machine data from JSON file (flows are now generated by LLM)"""
    # Get the directory of this file
    current_dir = os.path.dirname(os.path.abspath(__file__))
    full_path = os.path.join(current_dir, json_path)
    
    with open(full_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Convert machine dictionaries to Machine objects
    machines = [Machine(**m) for m in data['machines']]
    
    return machines


# Load data from JSON
MACHINES = load_data()

