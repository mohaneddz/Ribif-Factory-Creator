def scrape_from_source_reference(source_reference: str, cfg: EnrichConfig) -> Dict[str, Any]:
    scraped = {
        "image_urls": [],
        "datasheet_urls": [],
        "product_page_url": "",
        "manufacturer_website": "",
    }

    src = safe_s(source_reference, "")
    if not src.startswith("http"):
        return scraped

    try:
        polite_sleep(src, min_gap_s=cfg.domain_gap_s)
        html = fetch_html(src, timeout_s=cfg.http_timeout_s)
        base = f"{urlparse(src).scheme}://{urlparse(src).netloc}"
        imgs, pdfs = extract_links(html, base)
        scraped["image_urls"] = imgs[:20]
        scraped["datasheet_urls"] = pdfs[:10]
        scraped["product_page_url"] = src
        scraped["manufacturer_website"] = base
        return scraped
    except Exception:
        return scraped


def _time_left(t_start: float, budget_s: float) -> float:
    return budget_s - (time.time() - t_start)

def _budget_check(t_start: float, budget_s: float) -> bool:
    return (time.time() - t_start) <= budget_s


def _generate_green_bg_image(llm: VertexJSON, machine_final: Dict[str, Any], name: str, cfg: EnrichConfig, t_start: float) -> Optional[Dict[str, str]]:
    """
    1) Ask LLM for short image description
    2) Call Nano Banana
    3) Save file locally
    4) Return dict with local_path and logic for public_url
    """
    # --- budget gate
    if not _budget_check(t_start, cfg.total_machine_budget_s):
        return None

    # Step 1: short description
    left = max(5.0, _time_left(t_start, cfg.total_machine_budget_s))
    desc_raw = None
    try:
        # keep this fast
        desc_raw = llm.generate_raw(
            prompt=LLM_IMAGE_DESC_PROMPT.format(machine_final=json.dumps(machine_final, ensure_ascii=False)),
            temperature=0.2,
            timeout_s=min(int(cfg.llm_call_timeout_s), int(left)),
            system_instruction="Return ONLY plain text, 1-2 sentences. No JSON. No bullets.",
        )
        desc = _short(desc_raw, 300)
    except Exception:
        desc = f"Top view industrial machine for {safe_s(name,'unknown')}"

    if not _budget_check(t_start, cfg.total_machine_budget_s):
        return None

    # Step 2: Nano Banana image generation
    try:
        from vertex_utils import generate_image  # local import
    except Exception:
        return None

    prompt = NANO_BANANA_IMAGE_PROMPT.format(desc=desc)

    # Save bytes/base64 returned by generate_image
    out_dir = Path(cfg.generated_images_dir)
    ensure_dir(out_dir)
    filename = f"{slugify(name)}_{int(time.time())}.png"
    out_path = out_dir / filename

    try:
        img = generate_image(prompt=prompt)

        # Handle common return types
        final_bytes = None
        if isinstance(img, (bytes, bytearray)):
            final_bytes = bytes(img)
        elif isinstance(img, str):
            try:
                final_bytes = base64.b64decode(img)
            except Exception:
                pass
        elif isinstance(img, dict):
            for k in ("bytes", "image_bytes"):
                if k in img and isinstance(img[k], (bytes, bytearray)):
                    final_bytes = bytes(img[k])
                    break
            if not final_bytes:
                for k in ("b64", "base64"):
                    if k in img and isinstance(img[k], str):
                        try:
                            final_bytes = base64.b64decode(img[k])
                        except Exception:
                            pass
                        break
        
        if final_bytes:
            out_path.write_bytes(final_bytes)
            # Return valid structure
            # public_url will be formed by the route or client logic usually, 
            # but here we can return relative path or let downstream handle it.
            # We'll return the absolute local path and a placeholder for public URL.
            return {
                "local_path": str(out_path.resolve()),
                "filename": filename,
            }

    except Exception:
        pass
    
    return None


def enrich_one_machine(llm: VertexJSON, m: Dict[str, Any], cfg: EnrichConfig) -> Optional[Dict[str, Any]]:
    """
    Returns:
      - None if item is NOT a machine (filtered out)
      - dict if machine enriched (or fallback)
    """
    t_start = time.time()

    raw = normalize_raw_machine(m)
    name = safe_s(raw.get("nom_machine"), "unknown")

    # 0) Classify machine or not (fast)
    is_machine = llm.generate_bool_true_false(
        prompt=LLM_IS_MACHINE_PROMPT.format(raw_machine=json.dumps(raw, ensure_ascii=False)),
        tag=f"is_machine:{name}",
        timeout_s=min(cfg.llm_call_timeout_s, 10),  # keep classification fast
    )
    if is_machine is not True:
        return None

    # budget gate
    if not _budget_check(t_start, cfg.total_machine_budget_s):
        return {"machine_input": default_machine_final(name), "suppliers": default_suppliers(name), "skipped_reason": "budget>60s"}

    # scrape (optional)
    scraped = scrape_from_source_reference(
        source_reference=safe_s(raw.get("source_reference"), ""),
        cfg=cfg,
    )

    # NEW: Web search for specs/assets if enabled
    # NEW: Agentic Web search for specs/assets if enabled
    if WEB_SEARCH_ENABLED:
        try:
            from utils.web_search.agentic import agentic_search
            specs_result = agentic_search.search_specs_agentic(name, raw.get("fabricant_recommande") or "")
            if specs_result:
                # Merge found assets
                scraped["datasheet_urls"].extend(specs_result.datasheet_urls)
                scraped["image_urls"].extend(specs_result.image_urls)
                if specs_result.manufacturer_website:
                    scraped["manufacturer_website"] = specs_result.manufacturer_website
                
                # Pass detailed specs to LLM via scraped object
                scraped["agentic_specs"] = specs_result.specifications
                
                # Deduplicate
                scraped["datasheet_urls"] = list(set(scraped["datasheet_urls"]))
                scraped["image_urls"] = list(set(scraped["image_urls"]))
        except Exception as e:
            logger.warning("Agentic Web search specs failed for %s: %s", name, e)

    raw_machine = json.dumps(raw, ensure_ascii=False)
    scraped_assets = json.dumps(scraped, ensure_ascii=False)

    # 1) Finalize machine
    machine_final = llm.generate_json(
        LLM_FINAL_PROMPT.format(raw_machine=raw_machine, scraped_assets=scraped_assets),
        temperature=cfg.llm_temperature_final,
        tag=f"machine_final:{name}",
        timeout_s=cfg.llm_call_timeout_s,
    )
    if machine_final is None:
        machine_final = default_machine_final(name)
    
    # Ensure scraped assets are included if LLM missed them
    try:
        current_assets = machine_final.get("assets", {})
        
        # Merge images
        existing_imgs = set(current_assets.get("image_urls", []))
        for img in scraped.get("image_urls", []):
            if img not in existing_imgs:
                current_assets.setdefault("image_urls", []).append(img)
        
        # Merge datasheets
        existing_pdfs = set(current_assets.get("datasheet_urls", []))
        for pdf in scraped.get("datasheet_urls", []):
            if pdf not in existing_pdfs:
                current_assets.setdefault("datasheet_urls", []).append(pdf)
                
        machine_final["assets"] = current_assets
    except Exception:
        pass

    # budget gate
    if not _budget_check(t_start, cfg.total_machine_budget_s):
        return {
            "machine_input": machine_final,
            "suppliers": [],
            "skipped_steps": ["supplier_search", "image_generation"]
        }

    # 2) Suppliers
    suppliers = []
    web_suppliers_found = False
    
    if WEB_SEARCH_ENABLED:
        try:
            from utils.web_search.agentic import agentic_search
            # Search for real suppliers using Agentic approach
            web_results = agentic_search.search_suppliers_agentic(
                machine_name=name,
                machine_type=machine_final.get("type", ""),
                region="Algeria"
            )
            
            if web_results:
                suppliers = [s.to_dict() for s in web_results]
                web_suppliers_found = True
                logger.info("Found %d real suppliers for %s via Agentic Search", len(suppliers), name)
        except Exception as e:
            logger.warning("Agentic Web search suppliers failed for %s: %s", name, e)

    # Fallback: verified suppliers only. NO LLM GENERATION.
    if not web_suppliers_found:
        suppliers = []
        # If we had a mechanism to mark "no suppliers found", we do it here.
        # But per requirements: "If no verifiable suppliers... output 'suppliers': []"

    # Enforce provenance on suppliers
    valid_suppliers = []
    for s in suppliers:
        # simple check: must have name and at least one source url or website
        if s.get("supplier_name") and (s.get("source_urls") or s.get("website")):
             # ensure source_urls is list
             if "source_urls" not in s:
                 s["source_urls"] = [s["website"]] if s.get("website") else []
             if "evidence" not in s:
                 s["evidence"] = "Verified via Agentic Search"
             valid_suppliers.append(s)
    
    suppliers = valid_suppliers

    # budget gate
    if not _budget_check(t_start, cfg.total_machine_budget_s):
        return {
            "machine_input": machine_final, 
            "suppliers": suppliers, 
            "skipped_steps": ["image_generation"]
        }

    # 3) Generate best_image_url via Nano Banana (green bg)
        # Stored SEPARATELY in assets.generated_image
    gen_result = _generate_green_bg_image(llm, machine_final, name, cfg, t_start)
    if gen_result:
        # Don't overwrite best_image_url if we have real images
        # Check current best_image_url
        current_best = machine_final.get("best_image_url")
        has_real = current_best and current_best != "N/A"
        
        assets = machine_final.setdefault("assets", {})
        assets["generated_image"] = {
            "local_path": gen_result["local_path"],
            "filename": gen_result["filename"],
            "note": "AI generated green-bg render"
        }
        
        # If no real image found, we can optionally fallback best_image_url to this generated one,
        # but User Rule 4 says "Recommended: best_image_url = best real web image; Generated images go under assets.generated_image"
        # We will ONLY set best_image_url to generated if currently N/A or empty
        if not has_real:
             # We can't put a raw local path here usually, but we'll use a placeholder that the route can resolve,
             # or simply leave as N/A to be strict.
             # User requested "Never expose raw filesystem paths to frontend" in Fix 3.
             # So we will leave best_image_url as N/A here (since we don't have a public URL generator in core.py).
             # The route/frontend can use assets.generated_image if best_image_url is N/A.
             pass

    # best_image_url must be REAL (from image_urls) or N/A
    assets = machine_final.get("assets", {}) # Re-get assets after potential setdefault
    real_imgs = assets.get("image_urls", [])
    if real_imgs and isinstance(real_imgs, list) and len(real_imgs) > 0:
        machine_final["best_image_url"] = real_imgs[0]
    else:
        machine_final["best_image_url"] = "N/A"
        
    machine_final["assets"] = assets

    return {"machine_input": machine_final, "suppliers": suppliers}

def load_machines_from_module1(input_path: str) -> List[Dict[str, Any]]:
    data = json.load(open(input_path, "r", encoding="utf-8"))
    return data["stage_4_machines_equipements"]["machines_production"]

def build_machines_enriched(
    input_path: str,
    output_path: str,
    max_workers: int = DEFAULT_MAX_WORKERS,
    per_machine_timeout_s: int = DEFAULT_PER_MACHINE_TIMEOUT_S,
    domain_gap_s: float = DEFAULT_DOMAIN_GAP_S,
    llm_call_timeout_s: int = DEFAULT_LLM_CALL_TIMEOUT_S,
    total_machine_budget_s: int = DEFAULT_TOTAL_MACHINE_BUDGET_S,
    generated_images_dir: str = DEFAULT_GENERATED_IMAGES_DIR,
) -> Dict[str, Any]:
    t0 = time.time()
    p_in = Path(input_path)
    if not p_in.exists():
        raise FileNotFoundError(f"Input not found: {input_path}")

    machines = load_machines_from_module1(input_path)

    logger.info("=" * 70)
    logger.info("START RIBIF MODULE 4 — Parallel Machine Enrichment (Vertex-only)")
    logger.info("Input: %s", p_in.name)
    logger.info("max_workers: %s | items: %s", max_workers, len(machines))
    logger.info(
        "per_machine_timeout_s: %s | domain_gap_s: %s | llm_call_timeout_s: %s | budget_s: %s",
        per_machine_timeout_s,
        domain_gap_s,
        llm_call_timeout_s,
        total_machine_budget_s,
    )
    logger.info("generated_images_dir: %s", generated_images_dir)
    logger.info("=" * 70)

    llm = VertexJSON()
    logger.info("Vertex requested model: %s", llm.vertex_model)

    cfg = EnrichConfig(
        domain_gap_s=domain_gap_s,
        llm_call_timeout_s=llm_call_timeout_s,
        total_machine_budget_s=total_machine_budget_s,
        generated_images_dir=generated_images_dir,
    )

    results: List[Dict[str, Any]] = []
    warnings: List[str] = []
    filtered_non_machines = 0

    logger.info("START Launching enrichments in parallel...")
    with ThreadPoolExecutor(max_workers=max_workers) as ex:
        future_map: Dict[Any, Tuple[int, Dict[str, Any], float]] = {}

        # submit
        for i, m in enumerate(machines):
            name = safe_s(m.get("nom_machine"), f"item_{i+1}")
            logger.info("START SUBMIT [%s/%s] %s", i + 1, len(machines), name)
            fut = ex.submit(enrich_one_machine, llm, m, cfg)
            future_map[fut] = (i, m, time.time())  # correct timing

        # collect
        for fut in as_completed(future_map):
            i, m, t_start = future_map[fut]
            name = safe_s(m.get("nom_machine"), f"item_{i+1}")

            try:
                item = fut.result(timeout=per_machine_timeout_s)
                dt = time.time() - t_start

                if item is None:
                    filtered_non_machines += 1
                    logger.info("SKIP FILTER [%s/%s] %s (not a machine) in %.2fs", i + 1, len(machines), name, dt)
                    continue

                results.append(item)
                logger.info("DONE [%s/%s] %s in %.2fs", i + 1, len(machines), name, dt)

            except FuturesTimeoutError:
                warn = f"{name}: per-machine timeout after {per_machine_timeout_s}s, retrying once (temp=0.0)"
                warnings.append(warn)
                logger.warning("TIMEOUT %s -> retry once", name)

                try:
                    cfg2 = EnrichConfig(
                        domain_gap_s=domain_gap_s,
                        llm_temperature_final=0.0,
                        llm_temperature_suppliers=0.0,
                        llm_call_timeout_s=llm_call_timeout_s,
                        total_machine_budget_s=total_machine_budget_s,
                        generated_images_dir=generated_images_dir,
                    )
                    item = enrich_one_machine(llm, m, cfg2)

                    if item is None:
                        filtered_non_machines += 1
                        logger.info("SKIP FILTER RETRY %s (not a machine)", name)
                        continue

                    results.append(item)
                    logger.info("DONE RETRY SUCCESS %s", name)
                except Exception as e2:
                    warnings.append(f"{name}: retry failed: {e2}")
                    logger.error("ERROR RETRY FAIL %s -> %s", name, e2)

            except Exception as e:
                warnings.append(f"{name}: failed: {e}")
                logger.error("ERROR FAIL %s -> %s", name, e)

    processing_time = round(time.time() - t0, 3)

    out_obj = {
        "ribif_metadata": {
            "enrichment_method": "Module4 Parallel Machines (Vertex Gemini + Classify + Budget60s + GeneratedImage separate)",
            "enrichment_date": _now_iso(),
            "model_used": llm.vertex_model,
            "api_provider": "Vertex",
            "input_file": p_in.name,
            "items_in": len(machines),
            "machines_filtered_out": filtered_non_machines,
            "machines_out": len(results),
            "processing_time_seconds": processing_time,
            "note": ("Warnings: " + " ; ".join(warnings))[:4000] if warnings else "No warnings.",
        },
        "machines_enriched": results,
    }

    out_path = Path(output_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(out_obj, ensure_ascii=False, indent=2), encoding="utf-8")

    logger.info("=" * 70)
    logger.info("DONE MODULE 4")
    logger.info("Time: %.2fs", processing_time)
    logger.info("Saved: %s", out_path.resolve())
    logger.info("Filtered non-machines: %s", filtered_non_machines)
    if warnings:
        logger.warning("Warnings: %s (see ribif_metadata.note)", len(warnings))
    logger.info("=" * 70)

    return out_obj


