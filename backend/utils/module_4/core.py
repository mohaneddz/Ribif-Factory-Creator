_domain_last: Dict[str, float] = {}

def polite_sleep(url: str, min_gap_s: float = DEFAULT_DOMAIN_GAP_S) -> None:
    d = domain(url)
    now = time.time()
    last = _domain_last.get(d, 0.0)
    gap = now - last
    if gap < min_gap_s:
        time.sleep(min_gap_s - gap)
    _domain_last[d] = time.time()


