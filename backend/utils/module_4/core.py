def fetch_html(url: str, timeout_s: int = HTTP_TIMEOUT_S) -> str:
    r = requests.get(url, headers=HEADERS, timeout=timeout_s)
    r.raise_for_status()
    return r.text

def extract_links(html: str, base_url: str) -> Tuple[List[str], List[str]]:
    soup = BeautifulSoup(html, "html.parser")
    imgs: List[str] = []
    pdfs: List[str] = []

    for img in soup.find_all("img"):
        src = img.get("src") or ""
        if src.startswith("//"):
            src = "https:" + src
        if src.startswith("/"):
            src = base_url.rstrip("/") + src
        if src.startswith("http"):
            imgs.append(src)

    for a in soup.find_all("a"):
        href = a.get("href") or ""
        if href.startswith("//"):
            href = "https:" + href
        if href.startswith("/"):
            href = base_url.rstrip("/") + href
        if href.lower().endswith(".pdf") and href.startswith("http"):
            pdfs.append(href)

    def dedup(xs: List[str]) -> List[str]:
        seen = set()
        out: List[str] = []
        for x in xs:
            if x not in seen:
                seen.add(x)
                out.append(x)
        return out

    return dedup(imgs), dedup(pdfs)


