def _now_iso() -> str:
    return datetime.utcnow().isoformat()

def _short(s: str, n: int = 240) -> str:
    s = (s or "").replace("\n", " ").strip()
    return s if len(s) <= n else s[:n] + "..."

def _strip_code_fences(s: str) -> str:
    s = (s or "").strip()
    if s.startswith("```"):
        s = re.sub(r"^```[a-zA-Z0-9]*\s*", "", s)
        s = re.sub(r"\s*```$", "", s)
    return s.strip()

def _json_loads_relaxed(s: str) -> Any:
    """
    Robust JSON loader:
    - strips code fences
    - extracts first JSON object/array
    - removes trailing commas
    - converts fancy quotes
    """
    s = _strip_code_fences(s)

    try:
        return json.loads(s)
    except Exception:
        pass

    m = re.search(r"(\{[\s\S]*\}|\[[\s\S]*\])", s)
    if not m:
        raise ValueError("No JSON object/array found in output.")
    candidate = m.group(0)

    candidate = candidate.replace("\u201c", '"').replace("\u201d", '"')
    candidate = candidate.replace("\u2019", "'")
    candidate = re.sub(r",\s*(?=[}\]])", "", candidate)  # trailing commas

    # last resort: single to double quotes (risky but helps sloppy outputs)
    candidate = candidate.replace("'", '"')

    return json.loads(candidate)

def safe_s(v: Any, fallback: str) -> str:
    s = ("" if v is None else str(v)).strip()
    return s if s else fallback

def safe_i(v: Any, fallback: int) -> int:
    try:
        if v is None:
            return fallback
        if isinstance(v, int):
            return v
        return int(str(v).strip())
    except Exception:
        return fallback

def domain(url: str) -> str:
    try:
        return urlparse(url).netloc.lower()
    except Exception:
        return ""

def slugify(s: str) -> str:
    s = (s or "").strip().lower()
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "machine"

def ensure_dir(p: Path) -> None:
    p.mkdir(parents=True, exist_ok=True)


