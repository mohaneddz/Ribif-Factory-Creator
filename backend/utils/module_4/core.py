class VertexJSON:
    def __init__(self):
        load_dotenv()
        self.vertex_model = os.getenv("GEMINI_MODEL", "gemini-2.5-flash-lite")

    def generate_raw(
        self,
        prompt: str,
        temperature: float = 0.2,
        timeout_s: int = DEFAULT_LLM_CALL_TIMEOUT_S,
        system_instruction: Optional[str] = None,
    ) -> str:
        return generate_message_timeout(
            timeout_s=timeout_s,
            prompt=STRICT_JSON_HEADER + prompt,
            system_instruction=(system_instruction or SYSTEM_INSTRUCTION),
            temperature=temperature,
            top_p=0.95,
        )

    def generate_json(self, prompt: str, temperature: float, tag: str, timeout_s: int = DEFAULT_LLM_CALL_TIMEOUT_S) -> Any:
        try:
            raw = self.generate_raw(prompt, temperature=temperature, timeout_s=timeout_s)
            return _json_loads_relaxed(raw)
        except Exception as e:
            logger.error("%s: JSON generation failed, skipping. Reason: %s", tag, e)
            logger.error("Raw head: %s", _short(raw) if "raw" in locals() else "")
            return None

    def generate_bool_true_false(self, prompt: str, tag: str, timeout_s: int = DEFAULT_LLM_CALL_TIMEOUT_S) -> Optional[bool]:
        """
        Strict TRUE/FALSE classifier.
        """
        try:
            raw = generate_message_timeout(
                timeout_s=timeout_s,
                prompt=prompt,  # NOTE: no STRICT_JSON_HEADER here (we want raw token)
                system_instruction=(
                    "Return ONLY one token: TRUE or FALSE. "
                    "No JSON. No punctuation. No extra words."
                ),
                temperature=0.0,
                top_p=1.0,
            )
            token = (raw or "").strip().upper()
            if token.startswith("TRUE"):
                return True
            if token.startswith("FALSE"):
                return False
            return None
        except Exception as e:
            logger.error("%s: classifier failed: %s", tag, e)
            return None


